/** 호가 단위 — 가격대별로 굵게. 주문이 같은 값에 모여야 체결이 된다. */
function tickSize(price) {
  if (price < 2000) return 5;
  if (price < 5000) return 10;
  return 25;
}

/** 가격을 호가 단위에 맞춰 반올림 */
function roundToTick(price) {
  const t = tickSize(price);
  return Math.max(t, Math.round(price / t) * t);
}

